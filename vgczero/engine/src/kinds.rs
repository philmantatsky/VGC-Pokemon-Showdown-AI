/// Moves whose Showdown callbacks are fully reproduced by the engine's generic
/// handling of their data (side conditions, field effects, volatiles).
pub fn move_callbacks_are_generic(id: &str) -> bool {
    matches!(
        id,
        "tailwind"
            | "trickroom"
            | "gravity"
            | "reflect"
            | "lightscreen"
            | "safeguard"
            | "mist"
            | "raindance"
            | "sunnyday"
            | "sandstorm"
            | "snowscape"
            | "grassyterrain"
            | "psychicterrain"
            | "electricterrain"
            | "mistyterrain"
            | "confuseray"
            | "magnetrise"
            | "aquaring"
            | "ingrain"
            | "saltcure"
            | "laserfocus"
            | "charge"
            | "tarshot"
            | "smackdown"
            | "torment"
            | "healblock"
            | "attract"
    )
}
