//! Behaviour tags for abilities, items and scripted moves.
//!
//! Showdown implements these with event callbacks; the engine implements each
//! one explicitly at fixed hook points. An id that is not listed here maps to
//! `Other` / `MoveFx::None`, and the dex loader marks it unsupported if
//! Showdown gives it any scripted behaviour. Adding a variant here is a
//! promise that the battle code implements it.

macro_rules! tag_enum {
    ($name:ident { $($variant:ident = $id:literal),* $(,)? }) => {
        #[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, Default)]
        pub enum $name {
            #[default]
            Other,
            $($variant),*
        }
        impl $name {
            pub fn from_id(id: &str) -> $name {
                match id {
                    $($id => $name::$variant,)*
                    _ => $name::Other,
                }
            }
            pub const IMPLEMENTED: &'static [&'static str] = &[$($id),*];
        }
    };
}

